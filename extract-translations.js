#!/usr/bin/env node

/**
 * Writes the $t() strings in resources/admin to app/Services/TranslationStrings.php (don't
 * edit it by hand). Run after adding $t() calls. Strings with HTML, pure URLs and pure
 * numbers are skipped and reported: translators must not see markup, and those aren't text.
 */

const fs = require('fs');
const path = require('path');

const RESOURCES_DIR = path.join(__dirname, 'resources', 'admin');
const OUTPUT_FILE = path.join(__dirname, 'app', 'Services', 'TranslationStrings.php');
const TEXT_DOMAIN = 'wp-social-reviews';
const NAMESPACE = 'WPSocialReviews\\App\\Services';
const CLASS_NAME = 'TranslationStrings';

const TRANSLATION_PATTERNS = [
    /\$t\(\s*'([^']+)'\s*[\),]/g,
    /\$t\(\s*"([^"]+)"\s*[\),]/g,
    /this\.\$t\(\s*'([^']+)'\s*[\),]/g,
    /this\.\$t\(\s*"([^"]+)"\s*[\),]/g,
];

// ---- Validation filters ------------------------------------------------

const HTML_TAG_RE = /<[a-zA-Z\/][^>]*>/;

function isInvalid(str) {
    if (HTML_TAG_RE.test(str))      return 'contains HTML tags';
    if (/^https?:\/\//.test(str))   return 'pure URL';
    if (/^\d+(\.\d+)?$/.test(str))  return 'pure number';
    return null;
}

// ---- File traversal ----------------------------------------------------

function getFilesRecursively(dir, extensions = ['.vue', '.js']) {
    const files = [];

    if (!fs.existsSync(dir)) {
        return files;
    }

    for (const item of fs.readdirSync(dir)) {
        const fullPath = path.join(dir, item);
        if (fs.statSync(fullPath).isDirectory()) {
            files.push(...getFilesRecursively(fullPath, extensions));
        } else if (extensions.some(ext => item.endsWith(ext))) {
            files.push(fullPath);
        }
    }

    return files;
}

function extractStringsFromFile(filePath) {
    const content = fs.readFileSync(filePath, 'utf8');
    const strings = new Set();

    for (const pattern of TRANSLATION_PATTERNS) {
        pattern.lastIndex = 0;
        let match;
        while ((match = pattern.exec(content)) !== null) {
            const str = match[1].trim();
            if (str) {
                strings.add(str);
            }
        }
    }

    return Array.from(strings);
}

/**
 * Violations are collected separately so they get reported, not silently dropped.
 */
function extractStringsFromDirectory(dir) {
    const valid = new Set();
    const violations = [];   // [{ reason, string, file }]

    for (const file of getFilesRecursively(dir)) {
        for (const str of extractStringsFromFile(file)) {
            const reason = isInvalid(str);
            if (reason) {
                violations.push({ reason, string: str, file: path.relative(__dirname, file) });
            } else {
                valid.add(str);
            }
        }
    }

    return {
        strings: Array.from(valid).sort(),
        violations,
    };
}

// ---- PHP generation ----------------------------------------------------

// Same placeholder shape PHPCS's WordPress.WP.I18n sniff looks for.
const PLACEHOLDER_RE = /%(?:\d+\$)?[-+ 0']*\d*(?:\.\d+)?[bcdeEfFgGosuxX]/;

function generateArrayEntries(strings, indent = '            ') {
    return strings
        .map(str => {
            const key = str.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
            const entry = `${indent}'${key}' => __('${key}', '${TEXT_DOMAIN}'),`;
            if (!PLACEHOLDER_RE.test(str)) {
                return entry;
            }
            return `${indent}// translators: the placeholders are values the admin screen fills in at runtime; keep each one.\n${entry}`;
        })
        .join('\n');
}

function generatePHPClass(strings) {
    const timestamp = new Date().toISOString();

    return `<?php

namespace ${NAMESPACE};

/**
 * Auto-generated translation strings for WP Social Ninja admin.
 * Extracted from ${'$'}t() calls in Vue/JS files under resources/admin/.
 * Generated at: ${timestamp}
 *
 * DO NOT EDIT THIS FILE DIRECTLY.
 * Run 'node extract-translations.js' to regenerate.
 *
 * @package WPSocialReviews
 */

if (!defined('ABSPATH')) {
    exit;
}

class ${CLASS_NAME}
{
    /**
     * All admin UI strings extracted from Vue/JS ${'$'}t() calls.
     * Wrapped in __() so WordPress i18n tools include them in the POT file.
     *
     * @return array<string, string>
     */
    public static function getAdminStrings()
    {
        return [
${generateArrayEntries(strings)}
        ];
    }
}
`;
}

// ---- Main --------------------------------------------------------------

function main() {
    console.log('Extracting translation strings from WP Social Ninja admin...\n');

    const { strings, violations } = extractStringsFromDirectory(RESOURCES_DIR);

    const byReason = {};
    for (const v of violations) {
        (byReason[v.reason] = byReason[v.reason] || []).push(v);
    }

    if (violations.length > 0) {
        console.log('⚠  VIOLATIONS — these strings were SKIPPED and need source fixes:\n');
        for (const [reason, items] of Object.entries(byReason)) {
            console.log(`  [${reason}] (${items.length})`);
            const seen = new Set();
            for (const { string, file } of items) {
                if (seen.has(string)) continue;
                seen.add(string);
                const preview = string.length > 80 ? string.slice(0, 77) + '...' : string;
                console.log(`    "${preview}"`);
                console.log(`    → ${file}`);
            }
            console.log();
        }
    }

    const dir = path.dirname(OUTPUT_FILE);
    if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
    }

    fs.writeFileSync(OUTPUT_FILE, generatePHPClass(strings));

    console.log(`Generated: ${OUTPUT_FILE}`);
    console.log(`\n--- Summary ---`);
    console.log(`  Included: ${strings.length} strings`);
    console.log(`  Skipped:  ${violations.length} violations (${Object.keys(byReason).join(', ')})`);
    console.log(`\nDone!`);
}

main();
